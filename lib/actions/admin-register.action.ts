"use server";

import db from "@/db/drizzle";
import { user } from "@/db/schema";
import { requireRRASession } from "@/lib/auth-guard";
import { eq } from "drizzle-orm";

// ---------------------------------------------------------------------------
// Register a new taxpayer (admin-side)
// ---------------------------------------------------------------------------

export async function registerTaxpayer(data: {
    name: string;
    email: string;
    tinNumber: string;
    businessName: string;
    phoneNumber: string;
    role: "manufacturer" | "wholesaler" | "retailer";
}) {
    await requireRRASession("compliance_officer");

    // Validate required fields
    if (!data.name || !data.email || !data.tinNumber || !data.role) {
        throw new Error("Name, email, TIN, and role are required.");
    }

    // Check if TIN already exists
    const [existing] = await db
        .select({ id: user.id })
        .from(user)
        .where(eq(user.tinNumber, data.tinNumber))
        .limit(1);

    if (existing) {
        throw new Error("A trader with this TIN already exists.");
    }

    // Check if email already exists
    const [existingEmail] = await db
        .select({ id: user.id })
        .from(user)
        .where(eq(user.email, data.email))
        .limit(1);

    if (existingEmail) {
        throw new Error("A user with this email already exists.");
    }

    // Create user — id generated by the DB or crypto
    const id = crypto.randomUUID();
    await db.insert(user).values({
        id,
        name: data.name.trim(),
        email: data.email.trim(),
        tinNumber: data.tinNumber.trim(),
        username: data.tinNumber.trim(), // TIN as login username
        businessName: data.businessName.trim() || null,
        phoneNumber: data.phoneNumber.trim() || null,
        role: data.role,
        clearanceStatus: "approved",
        emailVerified: true,
        isActive: true,
    });

    return { id, success: true };
}
