"use server";

import db from "@/db/drizzle";
import { user } from "@/db/schema";
import { requireRRAPermission } from "@/lib/auth-guard";
import { eq } from "drizzle-orm";

// ---------------------------------------------------------------------------
// Register a new taxpayer (admin-side)
// ---------------------------------------------------------------------------

const NATIONAL_ID_REGEX = /^\d{16}$/;

export async function registerTaxpayer(data: {
    name: string;
    email: string;
    tinNumber: string;
    businessName: string;
    phoneNumber: string;
    role: "manufacturer" | "wholesaler" | "retailer";
    nationalIdNumber: string;
}) {
    await requireRRAPermission("taxpayer.registration.create");

    // Validate required fields
    if (!data.name || !data.email || !data.tinNumber || !data.role) {
        throw new Error("Name, email, TIN, and role are required.");
    }

    // Validate National ID — required, must be exactly 16 digits
    if (!data.nationalIdNumber || !NATIONAL_ID_REGEX.test(data.nationalIdNumber.trim())) {
        throw new Error("National ID must be exactly 16 digits.");
    }

    // Check if TIN already exists
    const [existing] = await db
        .select({ id: user.id })
        .from(user)
        .where(eq(user.tinNumber, data.tinNumber))
        .limit(1);

    if (existing) {
        throw new Error("A trader with this TIN already exists.");
    }

    // Check if email already exists
    const [existingEmail] = await db
        .select({ id: user.id })
        .from(user)
        .where(eq(user.email, data.email))
        .limit(1);

    if (existingEmail) {
        throw new Error("A user with this email already exists.");
    }

    // Check if National ID already exists
    const [existingNid] = await db
        .select({ id: user.id })
        .from(user)
        .where(eq(user.nationalId, data.nationalIdNumber.trim()))
        .limit(1);

    if (existingNid) {
        throw new Error("A trader with this National ID already exists.");
    }

    // Create user — id generated by crypto
    const id = crypto.randomUUID();
    await db.insert(user).values({
        id,
        name: data.name.trim(),
        email: data.email.trim(),
        tinNumber: data.tinNumber.trim(),
        username: data.tinNumber.trim(), // TIN as login username
        businessName: data.businessName.trim() || null,
        phoneNumber: data.phoneNumber.trim() || null,
        nationalId: data.nationalIdNumber.trim(),
        role: data.role,
        clearanceStatus: "approved",
        emailVerified: true,
        isActive: true,
    });

    return { id, success: true };
}
