import { requireRRASession } from '@/lib/auth-guard';
import { getFindings } from '@/lib/actions/ai-finding.action';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table';
import { FileSearch, Info } from 'lucide-react';
import Link from 'next/link';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function severityBadge(severity: string) {
  const cfg: Record<string, string> = {
    critical: 'bg-red-100 text-red-700 border-red-200',
    high:     'bg-orange-100 text-orange-700 border-orange-200',
    medium:   'bg-amber-100 text-amber-700 border-amber-200',
    low:      'bg-blue-100 text-blue-700 border-blue-200',
    info:     'bg-slate-100 text-slate-600 border-slate-200',
  };
  return (
    <Badge variant="outline" className={cfg[severity] ?? ''}>
      {severity}
    </Badge>
  );
}

function statusBadge(status: string) {
  const cfg: Record<string, string> = {
    open:         'bg-red-50 text-red-600 border-red-200',
    under_review: 'bg-amber-50 text-amber-700 border-amber-200',
    resolved:     'bg-emerald-50 text-emerald-700 border-emerald-200',
    dismissed:    'bg-slate-50 text-slate-500 border-slate-200',
  };
  return (
    <Badge variant="outline" className={cfg[status] ?? ''}>
      {status.replace('_', ' ')}
    </Badge>
  );
}

const TYPE_LABELS: Record<string, string> = {
  stock_discrepancy:   'Stock Discrepancy',
  underreporting:      'Underreporting',
  price_anomaly:       'Price Anomaly',
  tax_gap:             'Tax Gap',
  duplicate_transaction: 'Duplicate Transaction',
  supply_chain_gap:    'Supply Chain Gap',
  data_quality:        'Data Quality',
  risk_score:          'Risk Score',
};

// ---------------------------------------------------------------------------
// Page — searchParams for tab filter
// ---------------------------------------------------------------------------

interface SearchParams {
  status?: string;
  severity?: string;
  type?: string;
}

export default async function FindingsPage({
  searchParams,
}: {
  searchParams: Promise<SearchParams>;
}) {
  await requireRRASession("compliance_officer", "audit_officer", "tax_compliance_officer", "audit_investigation_officer", "data_ai_analyst");
  const params = await searchParams;

  let findings: Awaited<ReturnType<typeof getFindings>> = [];
  try {
    findings = await getFindings({
      reviewStatus: params.status as 'open' | 'under_review' | 'resolved' | 'dismissed' | undefined,
      severity:     params.severity as 'critical' | 'high' | 'medium' | 'low' | 'info' | undefined,
      findingType:  params.type as 'stock_discrepancy' | 'underreporting' | 'price_anomaly' | 'tax_gap' | 'duplicate_transaction' | 'supply_chain_gap' | 'data_quality' | 'risk_score' | undefined,
      limit:        100,
    });
  } catch {
    // Table may not exist yet
  }

  const TABS = [
    { label: 'All',          status: undefined },
    { label: 'Open',         status: 'open' },
    { label: 'Critical',     severity: 'critical' },
    { label: 'Under Review', status: 'under_review' },
    { label: 'Resolved',     status: 'resolved' },
  ];

  function tabHref(tab: { status?: string; severity?: string }) {
    const p = new URLSearchParams();
    if (tab.status)   p.set('status', tab.status);
    if ((tab as { severity?: string }).severity)  p.set('severity', (tab as { severity?: string }).severity!);
    return `/admin/intelligence/findings${p.toString() ? '?' + p.toString() : ''}`;
  }

  function isActiveTab(tab: { status?: string; severity?: string }) {
    const s = (tab as { severity?: string }).severity;
    if (s) return params.severity === s;
    if (tab.status) return params.status === tab.status;
    return !params.status && !params.severity && !params.type;
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="text-2xl font-bold tracking-tight">AI Findings</h1>
        <p className="text-muted-foreground text-sm mt-1">
          All intelligence findings generated by the AI reconciliation and anomaly engine.
        </p>
      </div>

      {/* Tab filter */}
      <div className="flex items-center gap-1 border-b">
        {TABS.map((tab) => (
          <Link
            key={tab.label}
            href={tabHref(tab)}
            className={`px-4 py-2 text-sm font-medium border-b-2 transition-colors ${
              isActiveTab(tab)
                ? 'border-foreground text-foreground'
                : 'border-transparent text-muted-foreground hover:text-foreground'
            }`}
          >
            {tab.label}
          </Link>
        ))}
      </div>

      {/* Table */}
      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-base font-semibold flex items-center gap-2">
            <FileSearch className="h-4 w-4 text-violet-500" />
            Findings ({findings.length})
          </CardTitle>
        </CardHeader>
        <CardContent className="p-0">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Type</TableHead>
                <TableHead>Severity</TableHead>
                <TableHead>Business</TableHead>
                <TableHead className="text-right">Observed</TableHead>
                <TableHead className="text-right">Expected</TableHead>
                <TableHead className="text-right">Difference</TableHead>
                <TableHead>Status</TableHead>
                <TableHead>Date</TableHead>
                <TableHead>Details</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {findings.length === 0 && (
                <TableRow>
                  <TableCell colSpan={9} className="py-12 text-center text-muted-foreground text-sm">
                    <div className="flex flex-col items-center gap-2">
                      <Info className="h-8 w-8 text-muted-foreground/40" />
                      <p>No findings found. The AI findings engine may not have run yet.</p>
                    </div>
                  </TableCell>
                </TableRow>
              )}
              {findings.map((f) => (
                <TableRow key={f.id} className="text-xs">
                  <TableCell className="font-medium">
                    {TYPE_LABELS[f.findingType] ?? f.findingType}
                  </TableCell>
                  <TableCell>{severityBadge(f.severity)}</TableCell>
                  <TableCell>
                    {f.businessId ? (
                      <Link
                        href={`/admin/intelligence/business/${f.businessId}`}
                        className="text-blue-600 hover:underline font-medium"
                      >
                        {f.businessName ?? f.businessId.slice(0, 8)}
                      </Link>
                    ) : (
                      <span className="text-muted-foreground">—</span>
                    )}
                    {f.tinNumber && (
                      <p className="text-[10px] text-muted-foreground font-mono">{f.tinNumber}</p>
                    )}
                  </TableCell>
                  <TableCell className="text-right font-mono">
                    {f.observedValue != null ? f.observedValue.toLocaleString() : '—'}
                  </TableCell>
                  <TableCell className="text-right font-mono">
                    {f.expectedValue != null ? f.expectedValue.toLocaleString() : '—'}
                  </TableCell>
                  <TableCell className={`text-right font-mono font-semibold ${
                    (f.difference ?? 0) < 0 ? 'text-red-600' : 'text-emerald-600'
                  }`}>
                    {f.difference != null ? f.difference.toLocaleString() : '—'}
                  </TableCell>
                  <TableCell>{statusBadge(f.reviewStatus)}</TableCell>
                  <TableCell className="text-muted-foreground">
                    {new Date(f.createdAt).toLocaleDateString()}
                  </TableCell>
                  <TableCell>
                    <Link
                      href={`/admin/intelligence/findings/${f.id}`}
                      className="text-blue-600 hover:underline text-[11px]"
                    >
                      View →
                    </Link>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      {/* Explanation column tooltip note */}
      {findings.length > 0 && (
        <p className="text-xs text-muted-foreground text-center">
          Click &quot;View →&quot; on any row to see the full explanation and evidence references.
        </p>
      )}
    </div>
  );
}
