// ── Seed ─────────────────────────────────────────────────────────────────────

async function seedTinFullDB(): Promise<void> {
  console.log('🌍 Starting comprehensive TIN DB seed — all 30 Rwanda districts...\n');

  try {
    console.log('  🗑  Clearing existing TIN data...');
    await db.delete(tinRecord);
    await db.delete(citizen);
    console.log('  ✓ Cleared\n');

    console.log(`  👤 Seeding ${CITIZENS.length} citizens...`);
    for (const c of CITIZENS) {
      await db.insert(citizen).values(c).onConflictDoNothing();
    }
    console.log(`  ✓ ${CITIZENS.length} citizens inserted\n`);

    console.log(`  🏢 Seeding ${TIN_RECORDS.length} TIN records...`);
    let mfgCount = 0,
      whoCount = 0,
      retCount = 0;
    for (const tin of TIN_RECORDS) {
      await db
        .insert(tinRecord)
        .values({
          ...tin,
          isActive: true,
        })
        .onConflictDoNothing();
      if (tin.businessType === 'manufacturer') mfgCount++;
      else if (tin.businessType === 'wholesaler') whoCount++;
      else retCount++;
    }
    console.log(
      `  ✓ ${TIN_RECORDS.length} businesses: ${mfgCount} manufacturers, ${whoCount} wholesalers, ${retCount} retailers\n`,
    );

    // Province summary
    const provinces: Record<string, number> = {};
    for (const tin of TIN_RECORDS) {
      provinces[tin.province] = (provinces[tin.province] ?? 0) + 1;
    }
    console.log('  📊 Distribution by province:');
    for (const [prov, count] of Object.entries(provinces)) {
      console.log(`     ${prov.padEnd(25)} ${count} businesses`);
    }

    const musanzeCount = TIN_RECORDS.filter((t) => t.district === 'Musanze').length;
    console.log(`\n  ✅ Musanze district has ${musanzeCount} traders (requirement: ≥4)`);
    console.log(`\n✅ TIN DB comprehensive seed complete!\n`);
  } catch (error) {
    console.error('❌ TIN seed failed:', error);
    throw error;
  } finally {
    await client.end();
  }
}

if (require.main === module) {
  seedTinFullDB()
    .then(() => process.exit(0))
    .catch(() => process.exit(1));
}

export default seedTinFullDB;
export { TIN_RECORDS, CITIZENS };
